"""Capability registry for every source the product is willing to name.

A row here is a declaration, not a promise that a live API exists. Live modules
register separately and must match an id in this list. Scores are 1–5, higher
is better. maintainability is the inverse of maintenance cost.
"""
from __future__ import annotations

from .types import CRITERIA, ConnectorSpec


def _score(user_value, api_access, completeness, reliability, privacy_legal, maintainability):
    return dict(zip(CRITERIA, (user_value, api_access, completeness, reliability, privacy_legal, maintainability)))


def _live(**kwargs) -> dict:
    base = dict(
        integration="official_api",
        mode="live",
        available=True,
        read_records=True,
        outbound=False,
        account_risk="",
        feature_flag=None,
        attachment_access="none",
        realtime="polling",
        content_access="metadata",
        read_history=True,
    )
    base.update(kwargs)
    return base


