def catalog() -> list[ConnectorSpec]:
    specs = [ConnectorSpec(**row) for row in _SPECS]
    ids = [spec.id for spec in specs]
    if len(ids) != len(set(ids)):
        raise RuntimeError("duplicate connector id")
    return specs


def catalog_by_id() -> dict[str, ConnectorSpec]:
    return {spec.id: spec for spec in catalog()}
